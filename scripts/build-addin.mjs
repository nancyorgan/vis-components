// Package the PowerPoint add-in's task pane for the self-host server:
// `node scripts/build-addin.mjs`, run by `pnpm build` after the frontend.
//
// Copies the task pane's files from addin/ into dist/addin/, and writes
// dist/addin/manifest.template.xml — the dev manifest (addin/manifest-
// taskpane.xml, which points at the addin-dev server on localhost) with its
// URLs turned into placeholders and its own add-in id. At startup the
// server installs dist/addin/ into its publish dir and fills the
// placeholders with VIS_PUBLISH_BASE_URL (server/src/addinFiles.ts), so
// each deployment serves a manifest.xml naming itself.
//
// One manifest source on purpose: the deployed manifest can't drift from
// the one sideloaded in development. The deployed add-in gets a different
// <Id> so a machine can have both installed side by side.
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const source = join(root, "addin")
const out = join(root, "dist", "addin")

// The task pane and what it loads. Not the content add-in experiment
// (content.*, manifest-live.xml) and not the dev manifest itself.
const FILES = [
	"taskpane.html",
	"taskpane.css",
	"taskpane.js",
	"zafiro.js",
	"icon-16.png",
	"icon-32.png",
	"icon-80.png",
]

const DEV_MANIFEST = "manifest-taskpane.xml"
const DEV_ORIGIN = "https://localhost:8443"
const DEV_ID = "7f3c2a9e-5b1d-4e8a-9c2f-0d6b1e4a7c31"
const DEPLOYED_ID = "8239a639-01f0-4a01-b9bf-db3247731b48"
// The placeholders server/src/addinFiles.ts fills in.
const BASE_URL = "{{ADDIN_BASE_URL}}"
const ORIGIN = "{{ADDIN_ORIGIN}}"
const TEMPLATE = "manifest.template.xml"

const fail = (message) => {
	console.error(`[build-addin] ${message}`)
	process.exit(1)
}

const count = (text, needle) => text.split(needle).length - 1

const devManifest = readFileSync(join(source, DEV_MANIFEST), "utf-8")
if (count(devManifest, `<Id>${DEV_ID}</Id>`) !== 1) {
	fail(`${DEV_MANIFEST} no longer has <Id>${DEV_ID}</Id>; update DEV_ID here.`)
}
if (count(devManifest, `${DEV_ORIGIN}/addin/`) === 0) {
	fail(`${DEV_MANIFEST} names no ${DEV_ORIGIN}/addin/ URLs; update DEV_ORIGIN here.`)
}

const body = devManifest
	// The dev-only header comment ("serve with pnpm addin:dev …").
	.replace(/<!--[\s\S]*?-->\s*/, "")
	.replaceAll(`${DEV_ORIGIN}/addin`, BASE_URL)
	.replaceAll(DEV_ORIGIN, ORIGIN)
	.replace(`<Id>${DEV_ID}</Id>`, `<Id>${DEPLOYED_ID}</Id>`)
if (/localhost/i.test(body)) fail(`a localhost URL survived templating ${DEV_MANIFEST}.`)
const template = body.replace(
	/^(<\?xml[^>]*\?>\s*)/,
	`$1<!-- Generated by scripts/build-addin.mjs from addin/${DEV_MANIFEST}. The\n` +
		`  self-host server fills in the URLs at startup (server/src/addinFiles.ts). -->\n`,
)

rmSync(out, { recursive: true, force: true })
mkdirSync(out, { recursive: true })
for (const name of FILES) copyFileSync(join(source, name), join(out, name))
writeFileSync(join(out, TEMPLATE), template)
console.log(`[build-addin] dist/addin/: ${FILES.length} files + ${TEMPLATE}`)
